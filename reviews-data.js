// Helper to render reviews in any container
window.renderGoogleReviews = function (containerId, filter = "all", limit = 6) {
  const container = document.getElementById(containerId);
  if (!container) return;

  let list = window.OSCA_REVIEWS || [];
  if (filter === "local-guide") {
    list = list.filter(r => r.isLocalGuide);
  } else if (filter !== "all") {
    list = list.filter(r => r.category === filter);
  }

  const items = limit > 0 ? list.slice(0, limit) : list;

  container.innerHTML = items.map(rev => `
    <div class="glass-card p-5 sm:p-6 rounded-2xl border border-slate-800 flex flex-col justify-between hover:border-cyan-400/30 transition-all group relative overflow-hidden">
      <!-- Watermark Google G -->
      <div class="absolute -right-4 -bottom-4 text-slate-800/20 text-7xl font-black pointer-events-none select-none group-hover:text-cyan-500/10 transition-colors">
        <i class="fa-brands fa-google"></i>
      </div>

      <div class="space-y-3 relative z-10">
        <!-- User Info -->
        <div class="flex items-start justify-between gap-3">
          <div class="flex items-center gap-3">
            <div class="w-10 h-10 rounded-full ${rev.avatarBg} text-white font-bold text-sm flex items-center justify-center shadow-md">
              ${rev.initial}
            </div>
            <div>
              <h4 class="text-sm font-bold text-white leading-tight flex items-center gap-1.5">
                ${rev.name}
              </h4>
              <span class="text-[10px] text-slate-400 flex items-center gap-1 mt-0.5">
                ${rev.isLocalGuide ? '<span class="text-amber-400 font-semibold flex items-center gap-0.5"><i class="fa-solid fa-star text-[9px]"></i> Local Guide</span> • ' : ''}${rev.badge.replace(/^Local Guide • /, '')}
              </span>
            </div>
          </div>
          <img src="https://upload.wikimedia.org/wikipedia/commons/c/c1/Google_%22G%22_logo.svg" alt="Google" class="w-4 h-4 opacity-80" />
        </div>

        <!-- Rating Stars -->
        <div class="flex items-center gap-2">
          <div class="flex text-amber-400 text-xs gap-0.5">
            ${'<i class="fa-solid fa-star"></i>'.repeat(rev.rating)}
          </div>
          <span class="text-[11px] text-slate-400">• ${rev.time}</span>
        </div>

        <!-- Review Text -->
        <p class="text-slate-300 text-xs sm:text-[13px] leading-relaxed italic">
          "${rev.text}"
        </p>
      </div>

      <!-- Verified Google Footer -->
      <div class="pt-4 mt-4 border-t border-slate-800/80 flex items-center justify-between text-[11px] text-slate-400 relative z-10">
        <span class="flex items-center gap-1 text-emerald-400 font-semibold">
          <i class="fa-solid fa-circle-check text-[10px]"></i> Verified Google Review
        </span>
        <a href="https://share.google/KetARk5s5CUDVXaoO" target="_blank" class="hover:text-cyan-400 transition-colors">
          View on Google &rarr;
        </a>
      </div>
    </div>
  `).join("");
};

// State trackers for filters and pagination
let _currentReviewFilter = "all";
let _isShowingAllReviews = false;

window.filterGoogleReviews = function (filter, btn) {
  _currentReviewFilter = filter;
  document.querySelectorAll(".review-tab-btn").forEach((b) => {
    b.classList.remove("active", "bg-cyan-400", "text-slate-950");
    b.classList.add("bg-slate-900", "text-slate-400");
  });
  if (btn) {
    btn.classList.add("active", "bg-cyan-400", "text-slate-950");
    btn.classList.remove("bg-slate-900", "text-slate-400");
  }
  const limit = _isShowingAllReviews ? 0 : 6;
  window.renderGoogleReviews("google-reviews-grid", _currentReviewFilter, limit);
};

window.toggleGoogleReviewsView = function () {
  _isShowingAllReviews = !_isShowingAllReviews;
  const toggleBtnText = document.getElementById("toggle-reviews-text");
  if (toggleBtnText) {
    toggleBtnText.textContent = _isShowingAllReviews ? "Show Fewer Reviews" : "Show All 20+ Google Reviews";
  }
  const limit = _isShowingAllReviews ? 0 : 6;
  window.renderGoogleReviews("google-reviews-grid", _currentReviewFilter, limit);
};

// Auto-initialize when DOM is ready
if (typeof document !== "undefined") {
  document.addEventListener("DOMContentLoaded", function () {
    if (document.getElementById("google-reviews-grid")) {
      window.renderGoogleReviews("google-reviews-grid", "all", 6);
    }
  });
}

